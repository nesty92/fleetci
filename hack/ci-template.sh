#!/bin/sh
# Prints a GitLab CI include with one hidden job per fleetci class, so a job
# picks its machine with one line:
#
#   include:
#     - local: .gitlab/fleetci.yml
#   build:
#     extends: .fleetci-4vcpu-6gb
#
# Usage: ci-template.sh <runner tag> <default class> <class>...
#
# A job's tags never reach the runner as variables, so the class travels in
# FLEETCI_CLASS; each hidden job sets the tag and the variable together. A
# misspelled class fails when the pipeline is created ("unknown extends"),
# before any VM boots.
set -eu
tag=$1 default=$2
shift 2

cat <<YAML
# fleetci classes for runner tag "$tag". Generated by fleetci; regenerate
# when the runner's classes change.
#
#   extends: .fleetci              # the default class, $default
#   extends: .fleetci-<class>      # one of the classes below

.fleetci:
  tags: [$tag]
YAML

for class in "$@"; do
  cat <<YAML

.fleetci-$class:
  extends: .fleetci
  variables:
    FLEETCI_CLASS: $class
YAML
done
